using APP.Services.Production;
using APP.Utils;
using INFRASTRUCTURE.Context;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Migrations;
using Npgsql;
using SHARED;
using SHARED.Services.Identity;
using Xunit;

namespace APP.Tests.FinishedGoods;

public sealed class FinishedGoodsPostgresFactAttribute : FactAttribute
{
    public FinishedGoodsPostgresFactAttribute() { if (string.IsNullOrWhiteSpace(Environment.GetEnvironmentVariable("ORYX_FG_TEST_CONNECTION"))) Skip = "Requires a disposable PostgreSQL test connection."; }
}
public sealed class FinishedGoodsPostgresTests
{
    private sealed class Actor(Guid user) : ICurrentUserService { public Guid? UserId => user; public Guid? DepartmentId => null; public string DepartmentType => ""; }
    [FinishedGoodsPostgresFact]
    public async Task Migrations_preserve_legacy_evidence_and_serializable_stock_writes_refuse_over_allocation()
    {
        var adminString = Environment.GetEnvironmentVariable("ORYX_FG_TEST_CONNECTION")!;
        var name = "oryx_fg_" + Guid.NewGuid().ToString("N");
        await using var admin = new NpgsqlConnection(adminString); await admin.OpenAsync();
        await new NpgsqlCommand($"CREATE DATABASE {name}", admin).ExecuteNonQueryAsync();
        try {
            var connection = new NpgsqlConnectionStringBuilder(adminString) { Database = name, Pooling = false }.ConnectionString;
            var actor = Guid.NewGuid(); var role = Guid.NewGuid(); var note = Guid.NewGuid();
            var options = new DbContextOptionsBuilder<ApplicationDbContext>().UseNpgsql(connection).Options;
            await using var db = new ApplicationDbContext(options, new Actor(actor));
            // The previous schema's principals, deliberately without unrelated ERP graphs.
            await db.Database.ExecuteSqlRawAsync("""
                CREATE TABLE users ("Id" uuid PRIMARY KEY,"IsDisabled" boolean NOT NULL DEFAULT false,"DeletedAt" timestamptz);
                CREATE TABLE roles ("Id" uuid PRIMARY KEY,"DeletedAt" timestamptz);
                CREATE TABLE userroles ("UserId" uuid,"RoleId" uuid);
                CREATE TABLE roleclaims ("Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"RoleId" uuid,"ClaimType" text,"ClaimValue" text);
                CREATE TABLE "PermissionTypes" ("Id" uuid PRIMARY KEY,"RoleClaimId" integer,"Key" text,"Type" text);
                CREATE TABLE "BatchManufacturingRecords" ("Id" uuid PRIMARY KEY);
                CREATE TABLE "ProformaInvoices" ("Id" uuid PRIMARY KEY);
                CREATE TABLE "Invoices" ("Id" uuid PRIMARY KEY);
                CREATE TABLE "Currencies" ("Id" uuid PRIMARY KEY);
                CREATE TABLE "AllocateProductionOrders" ("Id" uuid PRIMARY KEY);
                CREATE TABLE "ProductionOrderWaybills" ("Id" uuid PRIMARY KEY);
                CREATE TABLE "FinishedGoodsTransferNotes" ("Id" uuid PRIMARY KEY,"TotalQuantity" numeric NOT NULL,"QuantityReceived" numeric NOT NULL,"AllocatedQuantity" numeric NOT NULL);
                CREATE TABLE "__EFMigrationsHistory" ("MigrationId" varchar(150) PRIMARY KEY,"ProductVersion" varchar(32) NOT NULL);
                """);
            await db.Database.ExecuteSqlInterpolatedAsync($"INSERT INTO users (\"Id\") VALUES ({actor})");
            await db.Database.ExecuteSqlInterpolatedAsync($"INSERT INTO roles (\"Id\") VALUES ({role})");
            await db.Database.ExecuteSqlInterpolatedAsync($"INSERT INTO userroles VALUES ({actor},{role})");
            await db.Database.ExecuteSqlInterpolatedAsync($"INSERT INTO roleclaims (\"RoleId\",\"ClaimType\",\"ClaimValue\") VALUES ({role},'permission',{PermissionKeys.CanGeneratePackingList})");
            await db.Database.ExecuteSqlRawAsync("INSERT INTO \"PermissionTypes\" SELECT gen_random_uuid(),\"Id\",\"ClaimValue\",'Edit' FROM roleclaims");
            await db.Database.ExecuteSqlInterpolatedAsync($"INSERT INTO \"FinishedGoodsTransferNotes\" VALUES ({note},100,100,0)");
            await db.Database.ExecuteSqlInterpolatedAsync($"INSERT INTO roleclaims (\"RoleId\",\"ClaimType\",\"ClaimValue\") VALUES ({role},'permission',{PermissionKeys.CanSendProformaInvoice})");
            await db.Database.ExecuteSqlRawAsync("INSERT INTO \"PermissionTypes\" SELECT gen_random_uuid(),\"Id\",\"ClaimValue\",'Edit' FROM roleclaims WHERE \"ClaimValue\"='CanSendProformaInvoice'");
            var migrations = db.Database.GetMigrations().ToList();
            var first = migrations.Single(m => m.EndsWith("_HardenFinishedGoodsWorkflow"));
            var last = migrations.Single(m => m.EndsWith("_AddFinishedGoodsCostBasisAndRecallSettlements"));
            var script = db.GetService<IMigrator>().GenerateScript(migrations[migrations.IndexOf(first)-1], last);
            await db.Database.ExecuteSqlRawAsync(script);
            Assert.True(await db.Database.SqlQuery<bool>($"SELECT \"RequiresStockReconciliation\" AS \"Value\" FROM \"FinishedGoodsTransferNotes\" WHERE \"Id\"={note}").SingleAsync());
            Assert.Equal(100m, await db.Database.SqlQuery<decimal>($"SELECT \"TotalQuantity\" AS \"Value\" FROM \"FinishedGoodsTransferNotes\" WHERE \"Id\"={note}").SingleAsync());
            Assert.True(await db.Database.SqlQuery<bool>($"SELECT EXISTS (SELECT 1 FROM roleclaims WHERE \"RoleId\"={role} AND \"ClaimValue\"={PermissionKeys.CanVerifyFinishedGoodsCustomerPo}) AS \"Value\"").SingleAsync());
            Assert.False(await db.Database.SqlQuery<bool>($"SELECT EXISTS (SELECT 1 FROM roleclaims WHERE \"ClaimValue\"={PermissionKeys.CanReconcileFinishedGoodsStock}) AS \"Value\"").SingleAsync());
            var bothRead = new TaskCompletionSource(TaskCreationOptions.RunContinuationsAsynchronously); var readers = 0;
            async Task<Result> Reserve()
            {
                await using var session = new ApplicationDbContext(options, new Actor(actor));
                return await FinishedGoodsStock.Write(session, PermissionKeys.CanGeneratePackingList, actor, async () => {
                    var available = await session.Database.SqlQuery<decimal>($"SELECT \"QuantityReceived\"-\"AllocatedQuantity\" AS \"Value\" FROM \"FinishedGoodsTransferNotes\" WHERE \"Id\"={note}").SingleAsync();
                    if (Interlocked.Increment(ref readers) == 2) bothRead.SetResult();
                    await bothRead.Task.WaitAsync(TimeSpan.FromSeconds(20));
                    if (available < 80) return Error.Validation("Stock.Low", "Insufficient stock");
                    await session.Database.ExecuteSqlInterpolatedAsync($"UPDATE \"FinishedGoodsTransferNotes\" SET \"AllocatedQuantity\"=\"AllocatedQuantity\"+80 WHERE \"Id\"={note}");
                    return Result.Success();
                });
            }
            var results = await Task.WhenAll(Reserve(), Reserve()); Assert.Single(results.Where(r => r.IsSuccess));
            Assert.Single(results.Where(r => r.IsFailure && r.Error.Code == "FinishedGoods.Changed"));
            Assert.Equal(80m, await db.Database.SqlQuery<decimal>($"SELECT \"AllocatedQuantity\" AS \"Value\" FROM \"FinishedGoodsTransferNotes\" WHERE \"Id\"={note}").SingleAsync());
            await db.Database.ExecuteSqlRawAsync("DELETE FROM roleclaims");
            var denied = await FinishedGoodsStock.Write(db, PermissionKeys.CanGeneratePackingList, actor, () => Task.FromResult(Result.Success()));
            Assert.Equal(ErrorType.Forbidden, denied.Error.Type);
        }
        finally { await new NpgsqlCommand($"DROP DATABASE {name} WITH (FORCE)", admin).ExecuteNonQueryAsync(); }
    }
}
